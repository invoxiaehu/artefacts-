const RANG = { absent: 0, present: 1, correct: 2 };
const STEP = 260;

function tirageDuJour(len) {
  const liste = SOLUTIONS[len];
  const n = numeroDuJour() + (len === 6 ? 613 : 0);
  return liste[((n % liste.length) + liste.length) % liste.length];
}

function numeroDuJour() {
  const epoch = new Date(2026, 0, 1);
  const n = new Date();
  const d = new Date(n.getFullYear(), n.getMonth(), n.getDate());
  return Math.round((d - epoch) / 86400000);
}

function normaliser(txt) {
  return txt
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toUpperCase()
    .replace(/[^A-Z]/g, "");
}

function corriger(essai, mot) {
  const L = mot.length;
  const res = Array(L).fill("absent");
  const reste = {};
  for (let i = 0; i < L; i++) {
    if (essai[i] === mot[i]) res[i] = "correct";
    else reste[mot[i]] = (reste[mot[i]] || 0) + 1;
  }
  for (let i = 0; i < L; i++) {
    if (res[i] === "correct") continue;
    if (reste[essai[i]] > 0) {
      res[i] = "present";
      reste[essai[i]]--;
    }
  }
  return res;
}

function Marque({ etat, delay }) {
  const commun = {
    fill: "none",
    strokeLinecap: "round",
    strokeWidth: 2.6,
    strokeDasharray: 130,
    strokeDashoffset: 130,
    animation: `trace .35s ease-out ${delay}ms forwards`,
  };
  if (etat === "correct")
    return (
      <svg className="mark under" viewBox="0 0 60 10" preserveAspectRatio="none" aria-hidden="true">
        <path d="M1 6 C 18 3, 42 3, 59 6" stroke="#3F7A56" style={commun} />
      </svg>
    );
  if (etat === "present")
    return (
      <svg className="mark under" viewBox="0 0 60 12" preserveAspectRatio="none" aria-hidden="true">
        <path d="M1 7 q 7.25 -6 14.5 0 t 14.5 0 t 14.5 0 t 14.5 0" stroke="#B8842A" style={commun} />
      </svg>
    );
  return (
    <svg className="mark through" viewBox="0 0 60 6" preserveAspectRatio="none" aria-hidden="true">
      <path d="M2 4 C 20 1, 40 5, 58 2" stroke="#8C887C" style={commun} />
    </svg>
  );
}

